#!/usr/bin/env node
// Builds the chapter pages and the contents list. Run: node tools/build.js
//
// Input:  content/chapters.json          the book's parts, chapters, and appendices, in order
//         content/chapters/NN-slug.html  one HTML fragment per chapter (body only)
// Output: chapters/NN-slug.html          a full page per chapter
//         index.html                     the contents list, between the contents markers
//
// A fragment may use three shorthands, expanded here:
//   [[As Kh 7d]]   playing cards. Suits s h d c, x for "any suit", ?? for a face-down card.
//   {{ch:7}}       a link to Chapter 7 by title. {{ch:A}} links to Appendix A.
//   Fig. / Table   a figure-number of "Fig." or "Table" is numbered for you (Fig. 7.1, Table 7.2).
//
// The output is committed, so the site still opens straight from the files.
// tools/check.js fails if the output is stale. No dependencies.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const exists = (f) => fs.existsSync(path.join(root, f));
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const FONTS = 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,600;1,600&family=EB+Garamond:ital,wght@0,400;0,600;1,400&family=Josefin+Sans:wght@400;700&family=Limelight&display=swap';
const START = '<!-- contents:start (generated by tools/build.js, do not edit) -->';
const END = '<!-- contents:end -->';

// The flat list: chapters numbered 1, 2, 3; appendices lettered A, B, C.
function chapters() {
  const book = JSON.parse(read('content/chapters.json'));
  const list = [];
  let n = 0, a = 0;
  for (const part of book.parts) {
    for (const ch of part.chapters) {
      const id = part.appendix ? String.fromCharCode(65 + a++) : String(++n);
      const file = (part.appendix ? id.toLowerCase() : id.padStart(2, '0')) + '-' + ch.slug + '.html';
      list.push({
        ...ch, id, file, appendix: !!part.appendix,
        kind: part.appendix ? 'Appendix ' + id : 'Chapter ' + id,
        part: part.appendix ? part.title : 'Part ' + part.numeral + ': ' + part.title,
        written: exists('content/chapters/' + file)
      });
    }
  }
  return { book, list };
}

const SUITS = { s: ['♠', 'spades'], h: ['♥', 'hearts'], d: ['♦', 'diamonds'], c: ['♣', 'clubs'] };
const RANK_NAMES = { A: 'Ace', K: 'King', Q: 'Queen', J: 'Jack', T: 'Ten' };
// [[As Kh]] -> card markup that needs no script.
function expandCards(html) {
  return html.replace(/\[\[([^\]]*)\]\]/g, (m, inner) => {
    const names = [];
    const cards = inner.trim().split(/\s+/).map((tok) => {
      if (tok === '??') { names.push('a face-down card'); return '<span class="pc back"></span>'; }
      const c = tok.match(/^([AKQJT2-9])([shdcx])$/i);
      if (!c) throw new Error('Bad card "' + tok + '" in [[' + inner + ']]');
      const rank = c[1].toUpperCase(), suit = c[2].toLowerCase(), rn = RANK_NAMES[rank] || rank;
      if (suit === 'x') { names.push(rn); return '<span class="pc">' + rank + '</span>'; }
      names.push(rn + ' of ' + SUITS[suit][1]);
      return '<span class="pc' + (suit === 'h' || suit === 'd' ? ' r' : '') + '">' + rank + '<i>' + SUITS[suit][0] + '</i></span>';
    });
    return '<span class="cards" role="img" aria-label="' + names.join(', ') + '">' + cards.join('') + '</span>';
  });
}

// {{ch:7}} -> a link by title.
function expandRefs(html, list) {
  return html.replace(/\{\{ch:([0-9A-Za-z]+)\}\}/g, (m, id) => {
    const ch = list.find((c) => c.id === id.toUpperCase());
    if (!ch) throw new Error('Unknown chapter reference ' + m);
    return '<a class="xref" href="' + ch.file + '">' + ch.kind + ', ' + esc(ch.title) + '</a>';
  });
}

// "Fig." becomes "Fig. 4.1"; "Table" becomes "Table 4.1". Each kind has its own count.
function numberFigures(html, id) {
  const n = { 'Fig.': 0, Table: 0 };
  return html.replace(/(<span class="figure-number">)\s*(Fig\.|Table)\s*(<\/span>)/g, (m, open, kind, close) => open + kind + ' ' + id + '.' + (++n[kind]) + close);
}

function transform(fragment, ch, list) {
  return numberFigures(expandRefs(expandCards(fragment.trim()), list), ch.id);
}

function chapterPage(ch, prev, next, list, book) {
  const source = 'content/chapters/' + ch.file;
  const body = ch.written ? transform(read(source), ch, list) : '<p class="lead">This page has not been written yet. The book is being written and published one chapter at a time.</p>';
  const link = (c, rel, word) => c
    ? '<a class="chapter-nav-' + rel + '" href="' + c.file + '" rel="' + rel + '"><span class="label">' + word +
      '</span><span class="chapter-nav-title">' + (c.appendix ? c.id + '. ' : c.id + '. ') + esc(c.title) + '</span></a>'
    : '<span></span>';
  const scripts = body.includes('data-fig=') ? '\n  <script src="../js/figures.js"></script>' : '';

  return `<!doctype html>
<!-- Generated by tools/build.js from ${source}. Edit that file, not this one. -->
<html lang="en" data-style="blend">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${ch.id}. ${esc(ch.title)}: ${esc(book.title)}</title>
  <meta name="description" content="${esc(ch.summary)}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="${FONTS}" rel="stylesheet">
  <link rel="stylesheet" href="../css/themes.css">
  <link rel="stylesheet" href="../css/site.css">
</head>
<body>
  <div class="wrap">
    <header class="masthead label">
      <a href="../index.html">${esc(book.title)}</a>
      <span>${esc(ch.part)}</span>
    </header>

    <main>
      <article class="chapter">
        <header class="chapter-head">
          <p class="chapter-kicker label">${ch.kind} <span class="badge">${ch.written ? 'Preliminary draft' : 'To come'}</span></p>
          <h1 class="chapter-title">${esc(ch.title)}</h1>
          <p class="standfirst">${esc(ch.summary)}</p>
        </header>

        <div class="prose chapter-body">
${body}
        </div>
      </article>

      <nav class="chapter-nav" aria-label="Chapters">
        ${link(prev, 'prev', 'Previous')}
        ${link(next, 'next', 'Next')}
      </nav>
    </main>

    <footer class="colophon label">
      <nav>
        <a href="../index.html#contents">Contents</a>
        <a href="../docs/index.html">Docs</a>
        <a href="https://github.com/polarispixels/poker">GitHub</a>
      </nav>
      <span>Study notes, not advice. <span data-version></span></span>
    </footer>
  </div>

  <script src="../js/version.js"></script>${scripts}
</body>
</html>
`;
}

function contentsList(book, list) {
  let i = 0;
  const done = list.filter((c) => c.written).length;
  const parts = book.parts.map((part) => {
    const items = part.chapters.map(() => {
      const ch = list[i++];
      const inner = `<span class="contents-number">${ch.id}</span><span class="contents-text"><span class="contents-name">${esc(ch.title)}</span><span class="contents-summary">${esc(ch.summary)}</span></span>`;
      return ch.written
        ? `            <li><a href="chapters/${ch.file}">${inner}</a></li>`
        : `            <li class="to-come"><span class="contents-row">${inner}<span class="badge">To come</span></span></li>`;
    }).join('\n');
    return `        <div class="contents-part">
          <h3 class="label">${part.appendix ? esc(part.title) : 'Part ' + part.numeral + ': ' + esc(part.title)}<span class="contents-reader">${esc(part.reader)}</span></h3>
          <ol>
${items}
          </ol>
        </div>`;
  }).join('\n');
  return `${START}
      <section class="contents" id="contents" aria-labelledby="contents-title">
        <h2 class="contents-title" id="contents-title">Contents</h2>
        <p class="contents-progress label">${done} of ${list.length} pages written</p>
${parts}
      </section>
      ${END}`;
}

// Returns { path: content } for every generated file.
function build() {
  const { book, list } = chapters();
  const out = {};
  list.forEach((ch, idx) => { out['chapters/' + ch.file] = chapterPage(ch, list[idx - 1], list[idx + 1], list, book); });
  const home = read('index.html');
  const a = home.indexOf(START), b = home.indexOf(END);
  if (a < 0 || b < 0) throw new Error('index.html: contents markers not found');
  out['index.html'] = home.slice(0, a) + contentsList(book, list) + home.slice(b + END.length);
  return { out, list, book };
}

module.exports = { build, chapters, transform, expandCards };

if (require.main === module) {
  const { out } = build();
  fs.mkdirSync(path.join(root, 'chapters'), { recursive: true });
  for (const [file, content] of Object.entries(out)) fs.writeFileSync(path.join(root, file), content);
  console.log('Built ' + Object.keys(out).length + ' files');
}
